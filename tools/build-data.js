#!/usr/bin/env node
'use strict';
/**
 * Builds the two data scripts the page loads:
 *
 *   app/data/gear-data.js   every gear item in the game (data/catalog.json, the DB Inventory
 *                           Scanner's list read from Login.swz) plus rune, skill rune and magic
 *                           names (data/names.json, from the DPS Calculator's game data)
 *   app/data/seed-scans.js  the dbb-inventory scans in data/scans/, trimmed to what the page uses
 *
 * Run: node tools/build-data.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));

const catalog = read('data/catalog.json');
const names = read('data/names.json');
const drops = read('data/drops.json');

// Where each gear id comes from (data/drops.json, made by tools/extract_drops.py):
// [dungeonLevel, 'boss' | 'realm', boss or realm] per dungeon, or a single string for a special item.
const sourceOf = (id) => (drops.gear[String(id)] || []).map((s) => (s.special ? s.special : [s.dungeon, s.kind, s.by]));

// One row per item: [name, class, slot, gearId, tier, focus, procRunes, skillRune, magic, level, sources]
const gear = catalog.gear.map((g) => [g.n, g.c, g.s, g.id, g.t, g.f, g.p, g.k || '', g.m || '', g.l || 0, sourceOf(g.id)]);

const gearData = {
    version: 1,
    fields: ['name', 'class', 'slot', 'gearId', 'tier', 'focus', 'runes', 'skillRune', 'magic', 'level', 'sources'],
    gear,
    dungeons: drops.dungeons,
    runes: names.runes,
    skillRunes: names.skillRunes,
    magic: names.magic,
};

const scanDir = path.join(root, 'data/scans');
const scans = fs.readdirSync(scanDir).filter((f) => f.endsWith('.json')).sort().map((f) => {
    const s = JSON.parse(fs.readFileSync(path.join(scanDir, f), 'utf8'));
    if (s.format !== 'dbb-inventory') throw new Error(f + ': not a dbb-inventory scan');
    return trimScan(s);
});

function trimScan(s) {
    return {
        format: 'dbb-inventory',
        version: s.version,
        scannedAt: s.scannedAt,
        character: { name: s.character.name, class: s.character.class },
        gear: s.gear.map((g) => ({
            name: g.name, gearId: g.gearId, tier: g.tier, slot: g.slot, equipped: !!g.equipped,
            stats: g.stats || null, charms: g.charms || [],
        })),
    };
}

const banner = '// Generated by tools/build-data.js. Do not edit by hand.\n';
fs.writeFileSync(path.join(root, 'app/data/gear-data.js'), banner + 'window.DBB_GEAR = ' + JSON.stringify(gearData) + ';\n');
fs.writeFileSync(path.join(root, 'app/data/seed-scans.js'), banner + 'window.DBB_SEED_SCANS = ' + JSON.stringify(scans) + ';\n');
console.log('gear-data.js: %d items; seed-scans.js: %d scans (%s)', gear.length, scans.length,
    scans.map((s) => s.character.name + ' ' + s.gear.length).join(', '));

// gear.csv: every item with the page's columns, so the whole library is one file at /gear.csv.
const M = require('../app/model.js');
const { items } = M.buildItems(gearData, scans);
const cell = (v) => {
    const t = v === null || v === undefined ? '' : String(v);
    return /[",\n\r]/.test(t) ? '"' + t.replace(/"/g, '""') + '"' : t;
};
const order = (it) => [M.CLASSES.indexOf(it.cls), M.SLOTS.indexOf(it.slot), -it.tier, it.level];
items.sort((a, b) => {
    const x = order(a), y = order(b);
    for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return x[i] - y[i];
    return a.name.localeCompare(b.name);
});
const st = (it, f) => (it.stats ? (f === 'total' ? it.total : it.stats[f]) : '');
const header = ['Name', 'Class', 'Type', 'Rarity', 'Focus', 'Level', 'Attack', 'Expertise', 'Defense', 'Total', 'Rune 1', 'Rune 2', 'Skill rune', 'Magic',
    'Zone', 'Obtained in', 'Dropped by', 'Gear ID'];
const rows = items.map((it) => [it.name, it.cls, M.SLOT_NAME[it.slot], M.RARITY_NAME[it.rarity], M.FOCUS_NAME[it.focus], it.level,
    st(it, 'attack'), st(it, 'expertise'), st(it, 'defense'), st(it, 'total'), it.runeNames[0] || '', it.runeNames[1] || '', it.skillName, it.magicName,
    M.sourceZone(it), M.sourceText(it), M.droppedBy(it), it.id]);
fs.writeFileSync(path.join(root, 'gear.csv'), [header].concat(rows).map((r) => r.map(cell).join(',')).join('\r\n') + '\r\n');
console.log('gear.csv: %d rows', rows.length);
